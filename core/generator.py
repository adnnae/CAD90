"""Data file generator for legacy Fortran calculation engines.

Validated against real sample files (simple, DOUBLE, TRIPLE) generated by
DONCADRE_WIN64.EXE (doncadr.FOR).
"""

from pathlib import Path
from typing import Any, Dict, List

from .models import StructureType

FORMAT_VALIDATED = True

# Fixed reinforcement bar tables written by DONCADRE.EXE (lines 10-13)
_MAIN_BAR_COUNT = 11
_MAIN_BAR_DIAMS = [10.00, 12.00, 14.00, 15.03, 16.00, 18.11, 20.00, 22.64, 25.00, 28.71, 32.00]
_MAIN_BAR_LIMITS = [140.0, 170.0, 200.0, 250.0, 250.0, 320.0, 320.0, 400.0, 400.0, 640.0, 640.0]
_STIRRUP_COUNT = 3
_STIRRUP_DIAMS = [6.00, 8.00, 10.00]
_STIRRUP_LIMITS = [30.0, 30.0, 40.0]


def format_f(value: float, width: int, decimals: int, ms_fortran_no_leading_zero: bool = True) -> str:
    """Format a float using Fortran Fw.d fixed-width rules."""
    if decimals == 0:
        txt = f"{round(value):{width}.0f}."
        # e.g. 1350 -> " 1350." (width 6)
        txt = f"{int(round(value))}. "[:-1]
        txt = f"{int(round(value))}. "[:-1].rjust(width)
    else:
        txt = f"{value:{width}.{decimals}f}"
        if ms_fortran_no_leading_zero:
            # Microsoft Fortran 77 omits leading '0' for 0 <= x < 1: "  0.24" -> "   .24"
            if f"0.{'0' * decimals}" == txt.strip():
                txt = ("." + "0" * decimals).rjust(width)
            elif txt.lstrip().startswith("0."):
                stripped = txt.lstrip()[1:]  # ".24"
                txt = stripped.rjust(width)
    if len(txt) > width:
        raise ValueError(f"Value {value} overflows Fortran format F{width}.{decimals}: {txt!r}")
    return txt


def format_i(value: int, width: int) -> str:
    """Format an integer using Fortran Iw fixed-width rules."""
    txt = f"{int(value):{width}d}"
    if len(txt) > width:
        raise ValueError(f"Value {value} overflows Fortran format I{width}")
    return txt


def _chunked_line(items: List[str], per_line: int) -> List[str]:
    return ["".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]


class DataFileGenerator:
    """Generates input data files compatible with CASIMPLE, CADOUBLE, and CATRIPLE."""

    def generate(
        self,
        structure_type: StructureType,
        params: Dict[str, Any],
        output_dir: Path,
        allow_draft: bool = False,
    ) -> Path:
        """Write the data file in exact DONCADRE format into output_dir and return its path."""
        raw_name = str(params.get("nom_fichier", "DALOT01")).strip() or "DALOT01"
        safe_name = raw_name[:8]
        output_dir.mkdir(parents=True, exist_ok=True)
        target = output_dir / safe_name

        ouverture = float(params["ouverture"])
        gabarit = float(params["gabarit"])
        plate_forme = float(params["plate_forme"])
        poids_sup = float(params["poids_superstructures"])

        indice_ferr = int(params["indice_ferraillage"])
        indice_res = int(params["indice_resistance"])
        nb_cas = int(params["nb_cas_remblai"])
        charges_rout = int(params["charges_routieres"])

        hauteurs: List[float] = [float(x) for x in params["hauteurs_remblai"]]
        epaisseurs: List[float] = [float(x) for x in params["epaisseurs_cadre"]]
        if len(hauteurs) != nb_cas:
            raise ValueError(f"Nombre de hauteurs ({len(hauteurs)}) != nombre de cas ({nb_cas}).")
        if len(epaisseurs) != nb_cas:
            raise ValueError(f"Nombre d'épaisseurs ({len(epaisseurs)}) != nombre de cas ({nb_cas}).")

        nb_alveoles = {
            StructureType.SIMPLE: 1,
            StructureType.DOUBLE: 2,
            StructureType.TRIPLE: 3,
        }[structure_type]
        ouverture_totale = nb_alveoles * ouverture

        lines: List[str] = []

        # Line 01: (5f6.2, 4i4) -> I1=nb_cas, I2=indice_ferraillage, I3=indice_resistance, I4=1
        lines.append(
            format_f(ouverture, 6, 2)
            + format_f(gabarit, 6, 2)
            + format_f(plate_forme, 6, 2)
            + format_f(poids_sup, 6, 2)
            + format_f(epaisseurs[0], 6, 2)
            + format_i(nb_cas, 4)
            + format_i(indice_ferr, 4)
            + format_i(indice_res, 4)
            + format_i(1, 4)
        )

        # Line 02: (13f6.2) - hauteurs de remblai
        lines.extend(_chunked_line([format_f(h, 6, 2) for h in hauteurs], 13))

        # Line 03: (20f4.2) - epaisseurs du cadre
        lines.extend(_chunked_line([format_f(e, 4, 2) for e in epaisseurs], 20))

        # Line 04: (13f6.2) - ouverture totale = nb_alveoles * ouverture
        lines.append(format_f(ouverture_totale, 6, 2))

        # Line 05: (13f6.2)
        lines.extend(_chunked_line([format_f(0.0, 6, 2) for _ in range(nb_cas)], 13))

        # Line 06: (20i4)
        lines.extend(_chunked_line([format_i(0, 4) for _ in range(nb_cas)], 20))

        # Line 07: (13f6.4)
        lines.extend(_chunked_line([format_f(0.0, 6, 4) for _ in range(nb_cas)], 13))

        # Line 08: (6f6.2, 2f8.4, i4)
        lines.append(
            format_f(float(params["densite_remblai"]), 6, 2)
            + format_f(float(params["c1"]), 6, 2)
            + format_f(float(params["c2"]), 6, 2)
            + format_f(float(params["maj_c1"]), 6, 2)
            + format_f(float(params["maj_c2"]), 6, 2)
            + format_f(float(params["surcharge_remblai"]), 6, 2)
            + format_f(float(params["pente_horiz"]), 8, 4)
            + format_f(float(params["pente_vert"]), 8, 4)
            + format_i(charges_rout, 4)
        )

        # Line 09: (5f6.0, 4f6.2, 3f6.3) - stresses converted kg/cm2 -> t/m2 (*10), cover cm -> m (/100)
        lines.append(
            format_f(float(params["contrainte_beton_adm"]) * 10.0, 6, 0)
            + format_f(float(params["contrainte_beton_eco"]) * 10.0, 6, 0)
            + format_f(float(params["contrainte_beton_ref"]) * 10.0, 6, 0)
            + format_f(float(params["contrainte_acier_adm"]) * 10.0, 6, 0)
            + format_f(float(params["contrainte_etrier_adm"]) * 10.0, 6, 0)
            + format_f(float(params["densite_beton"]), 6, 2)
            + format_f(float(params["poisson"]), 6, 2)
            + format_f(float(params["longueur_barre"]), 6, 2)
            + format_f(float(params["equiv_acier_beton"]), 6, 2)
            + format_f(float(params["enrobage"]) / 100.0, 6, 3)
            + format_f(epaisseurs[0], 6, 3)
            + format_f(2.0, 6, 3)
        )

        # Line 10: (i4, 12f6.2)
        lines.append(format_i(_MAIN_BAR_COUNT, 4) + "".join(format_f(d, 6, 2) for d in _MAIN_BAR_DIAMS))

        # Line 11: (16f5.1)
        lines.append("".join(format_f(v, 5, 1) for v in _MAIN_BAR_LIMITS))

        # Line 12: (i4, 12f6.2)
        lines.append(format_i(_STIRRUP_COUNT, 4) + "".join(format_f(d, 6, 2) for d in _STIRRUP_DIAMS))

        # Line 13: (16f5.1)
        lines.append("".join(format_f(v, 5, 1) for v in _STIRRUP_LIMITS))

        target.write_bytes(("\r\n".join(lines) + "\r\n").encode("ascii"))
        return target
